def main():
    ap = argparse.ArgumentParser(
        description="Round-trip the manuscript through Overleaf.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Packages live outside the repository; ~/book-scratch/overleaf/ is the default,
and a path under the repository root is refused in both directions.

  overleaf.py export                    write the package
  overleaf.py import ZIP --dry-run      report, write nothing  DO THIS FIRST
  overleaf.py import ZIP                apply, repair, check

Set the compiler to LuaLaTeX in Overleaf (gear icon -> Compiler); the book does
not build under pdfLaTeX. The main document is book.tex. Retitling a section is
safe. Renumbering one, adding one, or deleting one is not, and stops the import
with nothing written.
""")
    sub = ap.add_subparsers(dest="cmd", required=True)

    e = sub.add_parser("export", help="write an Overleaf package")
    e.add_argument("-o", "--out",
                   help="zip to write, outside the repository "
                        "(default: ~/book-scratch/overleaf/"
                        "antifascist-intelligence_<date>.zip)")
    e.add_argument("--no-check", action="store_true",
                   help="skip check_all.sh before packaging")
    e.set_defaults(func=cmd_export)

    i = sub.add_parser("import", help="apply a zip downloaded from Overleaf")
    i.add_argument("zip", help="the zip from Overleaf (Menu -> Download -> "
                               "Source), from anywhere outside the repository")
    i.add_argument("--dry-run", action="store_true",
                   help="report what would happen and write nothing")
    i.add_argument("--allow-dirty", action="store_true",
                   help="import onto a tree with uncommitted changes")
    i.add_argument("--no-manifest-ok", action="store_true",
                   help="proceed with a zip that has no manifest, losing "
                        "the ability to tell an Overleaf edit from a repo one")
    i.add_argument("--force", action="store_true",
                   help="on a conflict, take Overleaf's copy")
    i.add_argument("--no-sync-titles", action="store_true",
                   help="do not update the title copies in ORDER.tsv, "
                        "outline.tsv and ledger.tsv after a retitle")
    i.set_defaults(func=cmd_import)

    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
