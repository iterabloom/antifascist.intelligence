#!/usr/bin/env python3
r"""Round-trip the manuscript through Overleaf: build a package, take the zip back.

`export` writes a zip Overleaf compiles as it stands. `import` applies an
Overleaf zip to the working tree and then repairs what the edit invalidated. The
two halves share a manifest carried inside the zip, and that manifest is what
makes the round trip safe rather than merely possible.

WHAT THE ROUND TRIP IS UP AGAINST. Three facts about this repository make an
unzip over the tree wrong:

  1. TWO FILES ARE GENERATED. `manuscript/sections.tex` comes from
     `sections/ORDER.tsv` by gen_book.py, and `manuscript/table-of-contents.txt`
     from the headings by headings.py. sections.tex has to be in the package or
     Overleaf cannot compile, so it goes out and is then IGNORED on the way back
     and regenerated instead. The TOC is not in the package at all.
  2. FOUR FILES CARRY EACH HEADING. The .tex heading is authoritative (D-011);
     ORDER.tsv, outline.tsv and ledger.tsv each keep a copy of the title. A
     retitle in Overleaf makes check_structure.py fail on ORDER.tsv, fatally.
     Import syncs all three copies and prints every line it changed.
  3. THE REPOSITORY MOVES WHILE THE AUTHOR EDITS. A pass can revise a section
     between the export and the import, and writing the Overleaf copy over it
     would revert that work with nothing on the page to say so. The manifest
     records both what was exported and what the repository held at the time, so
     import can tell "Overleaf changed this" from "the repository changed this"
     and refuses the case where both did.

THE ONE PATH REWRITE. preamble.tex reads `../finishing/refs.bib`, which escapes
the package root, and an Overleaf project has no path outside itself. Export
rewrites that one line to `refs.bib`; import reverses it. The reversal is an
exact match and is counted: if the line is not there to reverse, the file is
reported and not applied, rather than guessed at. Nothing else is rewritten --
book.tex and every section file travel byte for byte.

WHAT THIS DOES NOT DO, AND WILL NOT. It does not add, delete, renumber or move a
section. Those are structural and cost more than a file write: a new section
needs rows in ORDER.tsv, outline.tsv and ledger.tsv, and a renumber needs a
renumber-map plus a sweep of every `\ref` pointing at it. All four are DETECTED
and REPORTED, and the import writes nothing at all when it finds one, rather
than half-doing it.

It also cannot see anything the invariants do not cover. What comes back is
prose, and prose is read, not checked. `check_all.sh` runs at the end and its
result is printed; a green suite means the structure survived the trip, not that
the writing is good.

Packages live OUTSIDE the repository, in `~/book-scratch/overleaf/` by default,
next to where choose-a-random-page.py writes. A zip of the manuscript inside the
tree is a build product that would be committed, so both directions refuse a
path under the repository root rather than warning about it.

  export                          write the package    (~/book-scratch/overleaf/)
  import ZIP --dry-run            report, write nothing     ALWAYS DO THIS FIRST
  import ZIP                      apply, repair, check
"""
