def sha256(b):
    return hashlib.sha256(b).hexdigest()


def read_bytes(path):
    with open(path, "rb") as f:
        return f.read()


def git(*args, **kw):
    r = subprocess.run(("git",) + args, cwd=common.REPO,
                       capture_output=True, text=True)
    if kw.get("check", True) and r.returncode:
        sys.exit("git %s failed: %s" % (" ".join(args), r.stderr.strip()))
    return r.stdout.strip()


def run_tool(*argv):
    """Run one of the repository's own tools from the repo root, echoing it."""
    print("  $ %s" % " ".join(argv))
    cmd = list(argv)
    if cmd[0].endswith(".py"):
        cmd.insert(0, sys.executable)
    r = subprocess.run(cmd, cwd=common.REPO, capture_output=True, text=True)
    for line in (r.stdout + r.stderr).splitlines():
        print("    %s" % line)
    return r.returncode


def outside_repo(path, what):
    """Refuse a package path inside the repository, and say why.

    Both directions are checked. An exported zip inside the tree is a build
    product that would be committed; an imported one is the same file arriving,
    and `git status` would show it as untracked in the middle of a diff the
    author is trying to read.
    """
    real = os.path.realpath(path)
    repo = os.path.realpath(common.REPO)
    if real == repo or real.startswith(repo + os.sep):
        sys.exit("refusing: %s is inside the repository (%s).\n"
                 "  Packages belong outside it -- %s is the default.\n"
                 "  A zip of the manuscript in the tree is a build product, and\n"
                 "  it would land in the next commit."
                 % (what, os.path.relpath(real, repo), SCRATCH))


def zip_path_for(repo_path):
    """The package path a repository path travels as."""
    if repo_path == "finishing/refs.bib":
        return "refs.bib"
    if repo_path.startswith("manuscript/"):
        return repo_path[len("manuscript/"):]
    raise ValueError("no package path for %s" % repo_path)


def package_files():
    """[(zip path, repo path)] -- everything the package carries."""
    out = list(FIXED)
    _, rows = common.read_tsv(os.path.join(common.SECTIONS, "ORDER.tsv"))
    rows.sort(key=lambda r: common.numkey(r["num"]))
    for r in rows:
        out.append((zip_path_for(r["path"]), r["path"]))
    return out


def rewrite(zip_rel, text, forward):
    """Apply (forward) or reverse a package rewrite. Returns (text, error)."""
    for zp, repo_text, zip_text in REWRITES:
        if zp != zip_rel:
            continue
        src, dst = (repo_text, zip_text) if forward else (zip_text, repo_text)
        n = text.count(src)
        if n != 1:
            return None, ("expected exactly one %r, found %d -- the line the "
                          "package rewrites was edited or removed" % (src, n))
        text = text.replace(src, dst)
    return text, None


def normalize(raw, reference):
    """Decode a returned file, and report what had to be repaired to read it.

    Overleaf itself writes UTF-8 with LF endings. A file that has been through a
    Windows editor or a spreadsheet on the way can pick up CRLF or a BOM, and
    both would land in the manuscript as a real diff on every line.

    The final newline is restored only when the REFERENCE -- the repository's
    own copy -- has one. Imposing it as a convention instead manufactured an
    edit on the first test run: one file in the manuscript,
    sections/ch12/12_02_03.tex, ends without a newline, and normalizing it
    reported an Overleaf edit to a file nobody had opened.
    """
    notes = []
    if raw.startswith(b"\xef\xbb\xbf"):
        raw = raw[3:]
        notes.append("stripped a UTF-8 BOM")
    if b"\r\n" in raw:
        raw = raw.replace(b"\r\n", b"\n")
        notes.append("converted CRLF line endings to LF")
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as e:
        return None, ["not valid UTF-8 (%s)" % e]
    if text and not text.endswith("\n") and reference.endswith(b"\n"):
        text += "\n"
        notes.append("restored the final newline the repository's copy has")
    return text, notes


def set_tsv_cell(path, key_idx, key, val_idx, value):
    """Rewrite one cell of a TSV in place, by line, touching nothing else.

    Deliberately not common.write_tsv: that pads every row to the header width
    and would rewrite all 137 rows of a file to change one, burying the edit.
    """
    with open(path, encoding="utf-8", newline="") as f:
        lines = f.readlines()
    changed = False
    for i, line in enumerate(lines):
        if i == 0:
            continue
        nl = "\n" if line.endswith("\n") else ""
        parts = line.rstrip("\n").split("\t")
        if len(parts) <= max(key_idx, val_idx) or parts[key_idx] != key:
            continue
        if parts[val_idx] == value:
            return False
        parts[val_idx] = value
        lines[i] = "\t".join(parts) + nl
        changed = True
        break
    if changed:
        with open(path, "w", encoding="utf-8", newline="") as f:
            f.writelines(lines)
    return changed


def heading_of(text):
    """(command, starred, num, title) from a section file's text, else None."""
    lines = text.splitlines(True)
    if not lines:
        return None
    first = lines[0].rstrip("\n")
    m = common.TEX_HEAD_RE.match(first)
    if not m:
        return None
    starred = "*" in first.split("{", 1)[0]
    for line in lines[1:4]:
        lab = common.TEX_LABEL_RE.match(line.rstrip("\n"))
        if lab:
            return m.group(1), starred, lab.group(1), m.group(2).strip()
    return None


