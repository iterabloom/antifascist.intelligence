def extract(zip_file):
    """Read an Overleaf zip into {path: bytes}, safely. Returns (files, notes)."""
    notes = []
    members = {}
    total = 0
    with zipfile.ZipFile(zip_file) as zf:
        bad = zf.testzip()
        if bad is not None:
            sys.exit("import: the zip is corrupt at %s" % bad)
        for info in zf.infolist():
            name = info.filename
            if name.endswith("/"):
                continue
            # A symlink in a zip is a mode in the external attributes. Nothing
            # in this package is one; refuse rather than follow it anywhere.
            if (info.external_attr >> 16) & 0o170000 == 0o120000:
                notes.append("refused a symlink: %s" % name)
                continue
            norm = os.path.normpath(name.replace("\\", "/"))
            if os.path.isabs(norm) or norm.startswith("..") or \
                    ".." in norm.split("/"):
                notes.append("refused a path that escapes the package: %s" % name)
                continue
            if info.file_size > MAX_MEMBER_BYTES:
                notes.append("refused %s: %d bytes, over the %d-byte cap"
                             % (name, info.file_size, MAX_MEMBER_BYTES))
                continue
            total += info.file_size
            if total > MAX_TOTAL_BYTES:
                sys.exit("import: the zip expands past %d bytes; refusing"
                         % MAX_TOTAL_BYTES)
            members[norm] = zf.read(info)

    # Some browsers and file managers repack a download inside one folder.
    tops = {p.split("/", 1)[0] for p in members if "/" in p}
    roots = {p for p in members if "/" not in p}
    if not roots and len(tops) == 1:
        top = tops.pop()
        members = {p[len(top) + 1:]: b for p, b in members.items()}
        notes.append("stripped the wrapping directory %r from every path" % top)
    return members, notes


def ignorable(path):
    base = os.path.basename(path)
    if path.startswith("__MACOSX/") or base.startswith("._"):
        return True
    return base in IGNORE_NAME or path.endswith(IGNORE_SUFFIX)


def cmd_import(args):
    dry = args.dry_run
    zip_file = os.path.abspath(os.path.expanduser(args.zip))
    outside_repo(zip_file, "the zip")
    if not os.path.exists(zip_file):
        sys.exit("no such file: %s" % zip_file)
    print("== reading %s" % zip_file)
    members, notes = extract(zip_file)
    for n in notes:
        print("  %s" % n)
    print("  %d files in the zip" % len(members))

    if not dry:
        porcelain = git("status", "--porcelain")
        if porcelain and not args.allow_dirty:
            print()
            print("REFUSED: the working tree has uncommitted changes.")
            print("The import writes into the manuscript, and `git diff` is how")
            print("you read what it did; a dirty tree mixes the two. Commit or")
            print("stash first, or pass --allow-dirty if you mean to mix them.")
            for line in porcelain.splitlines()[:20]:
                print("  %s" % line)
            return 2

    # ---- the manifest, and what it is for -------------------------------
    manifest = None
    if MANIFEST in members:
        try:
            manifest = json.loads(members[MANIFEST].decode("utf-8"))
        except (ValueError, UnicodeDecodeError) as e:
            print("  the manifest is present but unreadable (%s)" % e)
    if manifest is None:
        print()
        print("NO MANIFEST in the zip (%s)." % MANIFEST)
        print("Without it there is no record of what was exported, so a file")
        print("that differs from the repository cannot be told apart two ways:")
        print("your edit in Overleaf, or a change made in the repository after")
        print("the export. Applying the second reverts work silently.")
        if not args.no_manifest_ok:
            print("Pass --no-manifest-ok to proceed anyway, having read that.")
            return 2
        print("Proceeding on --no-manifest-ok: every difference is treated as")
        print("an Overleaf edit, and `git diff` is the only check on that.")
    else:
        print("  manifest: exported %s from commit %s%s"
              % (manifest.get("exported", "?"), (manifest.get("commit") or "?")[:12],
                 ", tree dirty" if manifest.get("commit_dirty") else ""))

    known = {z: r for z, r in package_files()}
    base = (manifest or {}).get("files", {})

    apply_set = {}          # repo path -> new text
    unchanged, skipped, conflicts, problems, reports = [], [], [], [], []

    # ---- classify every file in the zip ----------------------------------
    for zip_rel in sorted(members):
        raw = members[zip_rel]
        if zip_rel in SCAFFOLD:
            continue
        if ignorable(zip_rel):
            skipped.append((zip_rel, "build product or OS file"))
            continue
        if zip_rel in GENERATED:
            skipped.append((zip_rel, "generated from ORDER.tsv; regenerated below"))
            continue
        repo_rel = known.get(zip_rel)
        if repo_rel is None:
            reports.append(("new file", zip_rel,
                            "not part of the package; a new section needs rows "
                            "in ORDER.tsv, outline.tsv and ledger.tsv, which "
                            "this tool does not write"))
            continue

        abs_repo = os.path.join(common.REPO, repo_rel)
        current = read_bytes(abs_repo) if os.path.exists(abs_repo) else b""
        text, norm_notes = normalize(raw, current)
        if text is None:
            problems.append("%s: %s" % (zip_rel, "; ".join(norm_notes)))
            continue
        for n in norm_notes:
            reports.append(("normalized", zip_rel, n))

        text, err = rewrite(zip_rel, text, forward=False)
        if err:
            problems.append("%s: %s" % (zip_rel, err))
            continue

        theirs = sha256(text.encode("utf-8"))
        ours = sha256(current) if current else None

        if theirs == ours:
            unchanged.append(zip_rel)
            continue

        rec = base.get(zip_rel)
        if rec is None:
            apply_set[repo_rel] = text          # no baseline: treat as an edit
            continue
        base_repo = rec.get("repo_sha256")
        if theirs == base_repo:
            # Overleaf did not touch it; the repository moved instead.
            skipped.append((zip_rel, "unedited in Overleaf; the repository "
                                     "changed it since the export"))
            continue
        if ours != base_repo and not args.force:
            conflicts.append(zip_rel)
            continue
        apply_set[repo_rel] = text

    # ---- files that were exported and did not come back ------------------
    for zip_rel in sorted(base):
        if zip_rel in members or zip_rel in SCAFFOLD:
            continue
        reports.append(("missing", zip_rel,
                        "exported but not in the returned zip; deleted or "
                        "renamed in Overleaf. Nothing is deleted here"))

    # ---- structural analysis, before anything is written -----------------
    _, order = common.read_tsv(os.path.join(common.SECTIONS, "ORDER.tsv"))
    by_path = {r["path"]: r for r in order}
    retitles = []
    for repo_rel, text in sorted(apply_set.items()):
        row = by_path.get(repo_rel)
        if row is None:
            continue                     # book.tex, preamble.tex, refs.bib
        h = heading_of(text)
        if h is None:
            problems.append("%s: no longer opens with a heading command and a "
                            "\\label{sec:N}; check_structure.py requires both"
                            % zip_path_for(repo_rel))
            continue
        cmd, starred, num, title = h
        # D-415: the depth a file must keep is the depth it left with, not one
        # derived from its number. D-406 made ORDER.tsv's num a stable identity
        # that matches the filename and the ledger key, so a num with three
        # dotted parts can legitimately print as a section -- chapter 13 has
        # three. common.level(num) read that as a depth change and returned 2
        # with nothing written, which would block an import over files Overleaf
        # never touched.
        abs_ours = os.path.join(common.REPO, repo_rel)
        ours_h = (heading_of(read_bytes(abs_ours).decode("utf-8"))
                  if os.path.exists(abs_ours) else None)
        # D-463, and the same correction one branch over: the label a file must
        # keep is the label it left with, not ORDER.tsv's num. D-461 made every
        # heading label a name -- sec:anyway, ch:route -- while num stays the
        # numeric identity the ledger is keyed on, so comparing the two called
        # every file a renumber and returned 2 with nothing written, over an
        # edit that changed one word. check_structure.py exempts a named label
        # from the same comparison for the same reason. Against the repository's
        # own copy the check still catches what it was built for: a label
        # changed in Overleaf, which is a renumber or a rename either way and
        # needs a map and a sweep of every \ref pointing at it.
        theirs = ours_h[2] if ours_h else row["num"]
        if num != theirs:
            problems.append("%s: the label came back as %s and the repository's "
                            "is %s. Changing a label needs a map and a sweep of "
                            "every \\ref pointing at it"
                            % (zip_path_for(repo_rel), num, theirs))
            continue
        want = ours_h[0] if ours_h else cmd
        if cmd != want:
            problems.append("%s: heading is \\%s and the repository's is \\%s. "
                            "Changing the depth renumbers the book"
                            % (zip_path_for(repo_rel), cmd, want))
            continue
        if title != row["title"]:
            retitles.append((num, row["title"], title))

    # ---- report ----------------------------------------------------------
    print()
    print("== what came back")
    print("  %d to apply, %d unchanged, %d skipped, %d conflicts, %d problems"
          % (len(apply_set), len(unchanged), len(skipped), len(conflicts),
             len(problems)))
    for repo_rel in sorted(apply_set):
        print("  edit      %s" % repo_rel)
    for zip_rel, why in sorted(skipped):
        print("  skip      %s -- %s" % (zip_rel, why))
    for kind, zip_rel, why in sorted(reports):
        print("  %-9s %s -- %s" % (kind, zip_rel, why))
    if retitles:
        print()
        print("== retitled sections (%d)" % len(retitles))
        for num, old, new in retitles:
            print("  %s" % num)
            print("    was: %s" % old)
            print("    now: %s" % new)

    if conflicts:
        print()
        print("== CONFLICTS (%d): changed in Overleaf AND in the repository"
              % len(conflicts))
        for zip_rel in conflicts:
            print("  %s" % zip_rel)
            print("    repo: %s" % known[zip_rel])
        print("Both versions moved since the export, so one of them would be")
        print("lost. Reconcile by hand -- the Overleaf text is in the zip and")
        print("the repository's is on disk -- or pass --force to take Overleaf's")
        print("and read `git diff` for what it overwrote.")

    if problems:
        print()
        print("== STRUCTURAL PROBLEMS (%d)" % len(problems))
        for p in problems:
            print("  %s" % p)
        print("Nothing was written. These are changes the repository has to make")
        print("itself: they touch ORDER.tsv, outline.tsv, ledger.tsv and the")
        print("cross-references, none of which are in the Overleaf package.")
        return 2

    if conflicts:
        print()
        print("Nothing was written.")
        return 2

    if not apply_set and not retitles:
        print()
        print("Nothing to apply: the zip matches the repository.")
        return 0

    if dry:
        print()
        print("--dry-run: nothing written. Re-run without it to apply.")
        return 0

    # ---- apply -----------------------------------------------------------
    print()
    print("== applying")
    for repo_rel, text in sorted(apply_set.items()):
        with open(os.path.join(common.REPO, repo_rel), "w",
                  encoding="utf-8", newline="") as f:
            f.write(text)
        print("  wrote %s" % repo_rel)

    if retitles and not args.no_sync_titles:
        print()
        print("== syncing the title copies (the .tex heading wins, D-011)")
        targets = [(os.path.join(common.SECTIONS, "ORDER.tsv"), 1, 2, "ORDER.tsv"),
                   (common.OUTLINE_TSV, 0, 1, "outline.tsv"),
                   (common.LEDGER_TSV, 0, 1, "ledger.tsv")]
        for num, _old, new in retitles:
            for path, key_idx, val_idx, label in targets:
                if not os.path.exists(path):
                    continue
                if set_tsv_cell(path, key_idx, num, val_idx, new):
                    print("  %-11s %s -> %s" % (label, num, new))
    elif retitles:
        print()
        print("  --no-sync-titles: the three title copies are left stale.")
        print("  check_structure.py will fail on ORDER.tsv until they are fixed.")

    # ---- repair ----------------------------------------------------------
    print()
    print("== regenerating what the edit invalidated")
    run_tool("finishing/tools/refresh_order_shas.py")
    run_tool("finishing/tools/gen_book.py")
    run_tool("finishing/tools/headings.py", "--write-toc")

    print()
    print("== invariants")
    rc = run_tool("bash", "finishing/tools/check_all.sh")

    print()
    print("Applied %d file(s)%s." % (len(apply_set),
                                     " and %d retitle(s)" % len(retitles)
                                     if retitles else ""))
    if rc:
        print("check_all.sh FAILED. Read it above; the tree is mid-repair.")
        print("`git diff` shows everything this import did, and `git checkout")
        print("--` on a path undoes it.")
    else:
        print("check_all.sh passed. Next:")
        print("  git diff                              read what changed")
        print("  finishing/tools/build_tex.sh          confirm it still builds")
    return 1 if rc else 0


