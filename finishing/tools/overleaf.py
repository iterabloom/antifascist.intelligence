README_TEMPLATE = """# Antifascist Intelligence -- Overleaf package

Built by `finishing/tools/overleaf.py export` on {date} from commit `{commit}`{dirty}.
{count} files: the master, the preamble, the generated input list, {nsec} section
files, and the bibliography.

## Before the first compile

**Set the compiler to LuaLaTeX.** Gear icon -> Compiler -> LuaLaTeX. The book
loads `fontspec` and will not build under pdfLaTeX. Overleaf's documentation
gives that menu as the way to set the compiler, so the package does not try to
set it from inside a file.

**The main document is `book.tex`.** Overleaf picks it by scanning for
`\\documentclass`, and `book.tex` is the only file in the package carrying one,
so a fresh upload should select it unaided. If it does not -- a project
remembers the main file it was given, so re-uploading into one that already
chose wrong keeps the wrong choice -- set it from the file tree: right-click
`book.tex` -> Set as Main File, or Menu -> Main document.

The symptom of the wrong main file is a build ending `<*> preamble.tex` and
`(job aborted, no legal \\end found)`. That is TeX handed a file with no
`\\begin{{document}}`, reading to the end looking for the matching `\\end`. It
means the entry point is wrong, not the package (D-170).

The bibliography is biblatex with the biber backend, which Overleaf runs on its
own. The body font is TeX Gyre Pagella, which ships with TeX Live; if the first
build cannot find it, that line is the second one in `preamble.tex`.

## What to edit

- `sections/chNN/*.tex` -- the prose, one file per section. This is the point.
- `preamble.tex` -- the typesetting.
- `book.tex` -- the master.
- `refs.bib` -- the bibliography.

## What not to do here

- **Do not edit `sections.tex`.** It is generated from `sections/ORDER.tsv` in
  the repository, and the import regenerates it. Edits are discarded.
- **Do not add, delete, rename or renumber section files.** Each section has
  rows in three tracking files and a `\\label` other sections point at, none of
  which are in this package. The import detects all four and stops without
  writing anything, so nothing is lost -- but the work has to be done in the
  repository instead.
- **Do not change a `\\label{{sec:N}}` line.** That is the section's number.
- **Do not move `\\documentclass` into `preamble.tex`.** It is in `book.tex` so
  that Overleaf's main-file detection lands on the master (D-170).
- **Retitling is fine.** Change the text inside `\\section{{...}}` and the import
  syncs the three copies the repository keeps of the title.
- **Do not delete `{manifest}`.** The import reads it to tell your edits from
  any the repository made while you were editing. Without it the import refuses
  to run unless it is forced past this.
- Straight quotes and `--` dashes fail the repository's typography check. Write
  the characters themselves: " " and -- (em) and - (en).

## Getting it back

Menu -> Download -> Source. Then, in the repository:

    python3 finishing/tools/overleaf.py import ~/Downloads/PROJECT.zip --dry-run
    python3 finishing/tools/overleaf.py import ~/Downloads/PROJECT.zip
    git diff
"""


def cmd_export(args):
    files = package_files()
    nsec = len(files) - len(FIXED)

    if not args.no_check:
        print("== invariants before export")
        rc = run_tool("bash", "finishing/tools/check_all.sh")
        if rc:
            print("  WARNING: check_all.sh fails on the tree being exported. The")
            print("  package is still written -- export reads and does not write --")
            print("  but whatever is broken travels with it.")

    commit = git("rev-parse", "HEAD")
    dirty = bool(git("status", "--porcelain"))
    date = datetime.datetime.now().strftime("%Y-%m-%d")

    if args.out is None:
        out = os.path.join(SCRATCH, "antifascist-intelligence_%s.zip" % date)
    else:
        out = os.path.abspath(os.path.expanduser(args.out))
    outside_repo(out, "the package")
    os.makedirs(os.path.dirname(out), exist_ok=True)

    manifest = {
        "format": 1,
        "tool": "finishing/tools/overleaf.py",
        "exported": datetime.datetime.now(datetime.timezone.utc)
                    .strftime("%Y-%m-%dT%H:%M:%SZ"),
        "commit": commit,
        "commit_dirty": dirty,
        "generated": sorted(GENERATED),
        "rewrites": [{"zip": z, "repo_text": r, "zip_text": p}
                     for z, r, p in REWRITES],
        "files": {},
    }

    staged = []
    for zip_rel, repo_rel in files:
        raw = read_bytes(os.path.join(common.REPO, repo_rel))
        repo_digest = sha256(raw)
        text, err = rewrite(zip_rel, raw.decode("utf-8"), forward=True)
        if err:
            sys.exit("export: %s: %s" % (repo_rel, err))
        blob = text.encode("utf-8")
        staged.append((zip_rel, blob))
        manifest["files"][zip_rel] = {
            "repo": repo_rel,
            "repo_sha256": repo_digest,     # the repository's bytes
            "zip_sha256": sha256(blob),     # what Overleaf was handed
        }

    readme = README_TEMPLATE.format(
        date=date, commit=commit[:12],
        dirty=" (with uncommitted changes in the tree)" if dirty else "",
        count=len(files), nsec=nsec, manifest=MANIFEST)

    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for zip_rel, blob in staged:
            zf.writestr(zip_rel, blob)
        zf.writestr(READMEF, readme.encode("utf-8"))
        zf.writestr(MANIFEST, (json.dumps(manifest, indent=2,
                                          sort_keys=True) + "\n").encode("utf-8"))

    size = os.path.getsize(out)
    print()
    print("wrote %s (%.1f MB)" % (out, size / 1e6))
    print("  %d files: %d section files, %s, plus %s and %s"
          % (len(files) + 2, nsec, ", ".join(z for z, _ in FIXED),
             READMEF, MANIFEST))
    print("  from commit %s%s" % (commit[:12],
                                  ", tree dirty" if dirty else ""))
    if dirty:
        print("  NOTE: uncommitted changes are in the package. The manifest")
        print("  records the working-tree bytes, so the round trip is still")
        print("  exact -- but the commit named above does not describe it.")
    print()
    print("Upload to Overleaf: New Project -> Upload Project -> this zip.")
    print("Then set the compiler to LuaLaTeX (gear icon -> Compiler); it does")
    print("not build under pdfLaTeX. The main document is book.tex, the only")
    print("file carrying \\documentclass, so Overleaf should select it unaided;")
    print("a build ending 'no legal \\end found' means it did not (D-170).")
    print("%s in the project repeats both." % READMEF)
    return 0


