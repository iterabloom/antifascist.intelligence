#!/usr/bin/env python3
r"""Translated editions: their section lists, their records, what has gone stale.

The English is the source. An edition lives in manuscript/<code>/, where <code>
is a language tag (uk, zh-tw, fa, ...): a hand-edited book.tex, a sections/
tree mirroring the English one, translations.tsv, glossary.tsv, and two
generated files, sections.tex and status.tex. Any directory under manuscript/
holding a translations.tsv is an edition.

A translated section is a translation of one English section file as it stood
at one moment, and translations.tsv records which moment: the English file's
sha256 when the translation was made or last brought up to date. When the
English changes, ORDER.tsv's digest moves and the two no longer match. That
mismatch is the whole staleness test.

What an edition prints for each English section file:
  - translated and current: the translation;
  - translated but stale:   the English, and the section is named in
                            status.tex, which the title page lists, so the
                            edition never prints a translation of English that
                            no longer exists;
  - not translated:         the English.
English sections are set under \selectlanguage{english}, for hyphenation; the
edition's book.tex points the English captions at its own.

  editions.py [--lang CODE]          write sections.tex and status.tex
                                     (every edition, or one)
  editions.py --check                validate every edition (stale listed,
                                     not failed); the check_all.sh entry
  editions.py --lang CODE --stale    list one edition's stale translations
  editions.py --lang CODE --diff PATH
                                     the English section PATH: what changed
                                     since the edition's translation of it
  editions.py --lang CODE --record PATH --status draft|reviewed --by WHO
                                     record that the translation of PATH now
                                     matches the English as it stands
"""
import argparse
import csv
import datetime
import difflib
import glob
import hashlib
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402

MANUSCRIPT = os.path.join(common.REPO, "manuscript")
RECORD_COLS = ["path", "uk_path", "source_sha256", "status", "by", "date"]
STATUSES = ("draft", "reviewed")


def editions():
    return sorted(os.path.basename(os.path.dirname(p))
                  for p in glob.glob(os.path.join(MANUSCRIPT, "*", "translations.tsv")))


def edir(code):
    return os.path.join(MANUSCRIPT, code)


def translated_path(code, path):
    """manuscript/sections/chNN/X.tex -> manuscript/<code>/sections/chNN/X.tex"""
    return path.replace("manuscript/sections/", "manuscript/%s/sections/" % code, 1)


def read_record(code):
    # The second column is named uk_path in every edition: it was the Ukrainian
    # edition's before there were others, and renaming it would rewrite history
    # for no gain. It holds the translated file's path, whatever the language.
    header, rows = common.read_tsv(os.path.join(edir(code), "translations.tsv"))
    if header != RECORD_COLS:
        sys.exit("%s/translations.tsv: header is %r, expected %r" % (code, header, RECORD_COLS))
    return rows


def write_record(code, rows):
    with open(os.path.join(edir(code), "translations.tsv"), "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(RECORD_COLS)
        for r in rows:
            w.writerow([r[c] for c in RECORD_COLS])


def stale(order, record):
    sha = {o["path"]: o["sha256"] for o in order}
    return [r for r in record if sha.get(r["path"]) != r["source_sha256"]]


def label_of(o):
    """How the title page names a section: its number, else its heading."""
    if o["num"]:
        return o["num"]
    if o["title"]:
        return o["title"]
    # A continuation file with no heading of its own; a part opener names its part.
    m = re.search(r"\\part\*?\{([^}]*)\}", open(os.path.join(common.REPO, o["path"]), encoding="utf-8").read())
    return ("Part: " + m.group(1)) if m else os.path.basename(o["path"])[:-4]


def expected(code, order, record):
    have = {r["path"]: r for r in record}
    old = {r["path"] for r in stale(order, record)}
    head = ("%% sections.tex -- GENERATED by finishing/tools/editions.py from\n"
            "%% sections/ORDER.tsv and %s/translations.tsv. Do not edit by hand.\n"
            "%% A current translation is input from %s/sections/ under the edition's\n"
            "%% language; an untranslated or stale section is the English file under\n"
            "%% \\selectlanguage{english}.\n" % (code, code))
    out = [head]
    stale_names = []
    for o in order:
        rel = os.path.relpath(os.path.join(common.REPO, o["path"]), MANUSCRIPT)[:-4]
        if o["path"] in have and o["path"] not in old:
            tr = os.path.relpath(os.path.join(common.REPO, have[o["path"]]["uk_path"]), MANUSCRIPT)[:-4]
            out.append("\\selectlanguage{\\booklanguage}\\input{%s}\n" % tr)
        else:
            if o["path"] in old:
                stale_names.append(label_of(o))
            out.append("\\selectlanguage{english}\\input{%s}\n" % rel)
    status = ("%% status.tex -- GENERATED by finishing/tools/editions.py. Do not edit.\n"
              "%% The sections whose translation is stale and which this edition\n"
              "%% therefore prints in English; book.tex lists them on the title page.\n"
              "\\def\\editionstalelist{%s}\n" % ", ".join(stale_names))
    return "".join(out), status


def head_and_label(path):
    """The heading command and the label line, which a translation must keep:
    the label so every \\ref resolves, the command so the structure holds."""
    cmd = label = None
    for line in open(path, encoding="utf-8"):
        m = common.TEX_HEAD_RE.match(line)
        if m and cmd is None:
            cmd = m.group(1)
        m = common.TEX_LABEL_RE.match(line)
        if m and label is None:
            label = line.strip()
    return cmd, label


def check(code, order, record):
    errors = []
    paths = {o["path"] for o in order}
    for r in record:
        if r["path"] not in paths:
            errors.append("%s: not in ORDER.tsv" % r["path"])
            continue
        if r["uk_path"] != translated_path(code, r["path"]):
            errors.append("%s: translated path %s, expected %s"
                          % (r["path"], r["uk_path"], translated_path(code, r["path"])))
        if not re.fullmatch(r"[0-9a-f]{64}", r["source_sha256"]):
            errors.append("%s: source_sha256 is not a sha256" % r["path"])
        if r["status"] not in STATUSES:
            errors.append("%s: status %r, expected one of %s" % (r["path"], r["status"], STATUSES))
        tf = os.path.join(common.REPO, r["uk_path"])
        if not os.path.exists(tf):
            errors.append("%s: missing" % r["uk_path"])
            continue
        if head_and_label(tf) != head_and_label(os.path.join(common.REPO, r["path"])):
            errors.append("%s: heading command or label differs from the English" % r["uk_path"])
    if len({r["path"] for r in record}) != len(record):
        errors.append("translations.tsv: a section is recorded twice")
    listed = {r["uk_path"] for r in record}
    for f in sorted(glob.glob(os.path.join(edir(code), "sections", "ch*", "*.tex"))):
        rel = os.path.relpath(f, common.REPO)
        if rel not in listed:
            errors.append("%s: not recorded in translations.tsv" % rel)
    gl = os.path.join(edir(code), "glossary.tsv")
    if os.path.exists(gl):
        header, rows = common.read_tsv(gl)
        want = ["en", code, "status", "note"]
        if header != want:
            errors.append("glossary.tsv: header is %r, expected %r" % (header, want))
        else:
            seen = set()
            for g in rows:
                if g["status"] not in ("proposed", "approved"):
                    errors.append("glossary.tsv: %r has status %r" % (g["en"], g["status"]))
                if g["en"] in seen:
                    errors.append("glossary.tsv: %r listed twice" % g["en"])
                seen.add(g["en"])
    want_sections, want_status = expected(code, order, record)
    for name, want in (("sections.tex", want_sections), ("status.tex", want_status)):
        p = os.path.join(edir(code), name)
        got = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if got != want:
            errors.append("%s/%s is stale: run finishing/tools/editions.py" % (code, name))
    return ["%s: %s" % (code, e) for e in errors]


def english_at(path, sha):
    """The English file's text when its sha256 was `sha`: the working tree if
    it still matches, else the newest commit whose version of the file does."""
    cur = os.path.join(common.REPO, path)
    if os.path.exists(cur) and hashlib.sha256(open(cur, "rb").read()).hexdigest() == sha:
        return open(cur, encoding="utf-8").read()
    revs = subprocess.run(["git", "log", "--format=%H", "--", path], cwd=common.REPO,
                          capture_output=True, text=True, check=True).stdout.split()
    for rev in revs:
        blob = subprocess.run(["git", "show", "%s:%s" % (rev, path)], cwd=common.REPO,
                              capture_output=True, check=False).stdout
        if hashlib.sha256(blob).hexdigest() == sha:
            return blob.decode("utf-8")
    return None


def word_diff(old, new):
    """Changed paragraphs only (a paragraph is a source line), each with its
    changes marked word by word and a little context either side."""
    out = []
    lines = difflib.SequenceMatcher(None, old.splitlines(), new.splitlines(), autojunk=False)
    ol, nl = old.splitlines(), new.splitlines()
    for tag, i1, i2, j1, j2 in lines.get_opcodes():
        if tag == "equal":
            continue
        a, b = " ".join(ol[i1:i2]).split(" "), " ".join(nl[j1:j2]).split(" ")
        words = difflib.SequenceMatcher(None, a, b, autojunk=False)
        parts = []
        for t, x1, x2, y1, y2 in words.get_opcodes():
            if t == "equal":
                seg = a[x1:x2]
                if len(seg) > 16:
                    seg = seg[:8] + ["…"] + seg[-8:]
                parts.append(" ".join(seg))
            else:
                if x2 > x1:
                    parts.append("[-%s-]" % " ".join(a[x1:x2]))
                if y2 > y1:
                    parts.append("{+%s+}" % " ".join(b[y1:y2]))
        out.append("@@ source lines %d-%d -> %d-%d\n%s" % (i1 + 1, i2, j1 + 1, j2, " ".join(parts)))
    return "\n\n".join(out) if out else "(no change)"


def write_generated(code, order, record):
    sections, status = expected(code, order, record)
    for name, text in (("sections.tex", sections), ("status.tex", status)):
        with open(os.path.join(edir(code), name), "w", encoding="utf-8") as f:
            f.write(text)
    st = stale(order, record)
    print("%s: wrote sections.tex and status.tex (%d of %d sections translated, %d stale)"
          % (code, len(record), len(order), len(st)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lang")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stale", action="store_true")
    ap.add_argument("--diff", metavar="PATH")
    ap.add_argument("--record", metavar="PATH")
    ap.add_argument("--status", choices=STATUSES)
    ap.add_argument("--by")
    ap.add_argument("--date", default=datetime.date.today().isoformat())
    a = ap.parse_args()
    order = common.order_rows()
    codes = editions()
    if a.lang:
        if a.lang not in codes:
            sys.exit("no edition %r (editions: %s)" % (a.lang, ", ".join(codes) or "none"))
        codes = [a.lang]
    elif a.stale or a.diff or a.record:
        sys.exit("--stale, --diff and --record need --lang")

    if a.check:
        errors = []
        for code in codes:
            record = read_record(code)
            for r in stale(order, record):
                print("STALE: %s (translated from English %s; printed in English until updated)"
                      % (r["uk_path"], r["source_sha256"][:12]))
            errs = check(code, order, record)
            errors += errs
            if not errs:
                print("%s edition OK: %d of %d section files translated, %d stale"
                      % (code, len(record), len(order), len(stale(order, record))))
        for e in errors:
            print("ERROR: %s" % e)
        if not codes:
            print("no translated editions")
        return 1 if errors else 0

    code = codes[0] if a.lang else None
    if a.stale:
        for r in stale(order, read_record(code)):
            print("STALE: %s" % r["path"])
        return 0

    if a.diff:
        rec = next((r for r in read_record(code) if r["path"] == a.diff), None)
        if rec is None:
            sys.exit("%s has no %s translation" % (a.diff, code))
        old = english_at(a.diff, rec["source_sha256"])
        if old is None:
            sys.exit("the English %s translated from (%s) is in neither the tree nor the history"
                     % (a.diff, rec["source_sha256"][:12]))
        new = open(os.path.join(common.REPO, a.diff), encoding="utf-8").read()
        print("%s: English as translated (%s) -> now; [-removed-] {+added+}"
              % (a.diff, rec["source_sha256"][:12]))
        print(word_diff(old, new))
        return 0

    if a.record:
        if not (a.status and a.by):
            sys.exit("--record needs --status and --by")
        row = next((o for o in order if o["path"] == a.record), None)
        if row is None:
            sys.exit("%s is not in ORDER.tsv" % a.record)
        tp = translated_path(code, a.record)
        if not os.path.exists(os.path.join(common.REPO, tp)):
            sys.exit("%s does not exist; write the translation first" % tp)
        record = [r for r in read_record(code) if r["path"] != a.record]
        record.append({"path": a.record, "uk_path": tp, "source_sha256": row["sha256"],
                       "status": a.status, "by": a.by, "date": a.date})
        seq = {o["path"]: i for i, o in enumerate(order)}
        record.sort(key=lambda r: seq.get(r["path"], 1 << 30))
        write_record(code, record)
        print("%s: recorded %s (%s, %s) against English %s"
              % (code, a.record, a.status, a.by, row["sha256"][:12]))

    for c in codes:
        write_generated(c, order, read_record(c))
    return 0


if __name__ == "__main__":
    sys.exit(main())
