#!/usr/bin/env python3
r"""The Ukrainian edition: its section list, its record, and what has gone stale.

The English is the source. A Ukrainian section is a translation of one English
section file, made from that file as it stood at one moment, and
manuscript/uk/translations.tsv records which moment: the English file's sha256
when the translation was made (or last brought up to date). When the English
changes, ORDER.tsv's digest moves and the two no longer match. That mismatch is
the whole of the staleness test, so a translation can't fall behind silently.

Chapters are translated one at a time, once the author calls a chapter's
English settled. Until a section has a translation, the Ukrainian build sets
the English file in its place, as English, so the edition always builds whole
and every cross-reference resolves.

  uk_edition.py                  write manuscript/uk/sections.tex
  uk_edition.py --check          validate the record, the files and the
                                 glossary; confirm sections.tex is current;
                                 list stale translations (listed, not failed)
  uk_edition.py --stale          list stale translations only
  uk_edition.py --record PATH --status draft|reviewed --by WHO [--date D]
                                 record that the Ukrainian for English section
                                 PATH now matches the English as it stands
"""
import argparse
import csv
import datetime
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402

UK = os.path.join(common.REPO, "manuscript", "uk")
RECORD = os.path.join(UK, "translations.tsv")
GLOSSARY = os.path.join(UK, "glossary.tsv")
OUT = os.path.join(UK, "sections.tex")
RECORD_COLS = ["path", "uk_path", "source_sha256", "status", "by", "date"]
GLOSSARY_COLS = ["en", "uk", "status", "note"]
STATUSES = ("draft", "reviewed")

HEAD = """% sections.tex -- GENERATED by finishing/tools/uk_edition.py from
% sections/ORDER.tsv and uk/translations.tsv. Do not edit by hand.
% A translated section is input from uk/sections/ under
% \\selectlanguage{ukrainian}; an untranslated one is the English file under
% \\selectlanguage{english}. Commands, not environments, so no group is held
% open around a whole chapter; uk/book.tex points the English captions at the
% Ukrainian ones, so an English section still heads as Розділ.
"""


def uk_path_for(path):
    """manuscript/sections/chNN/X.tex -> manuscript/uk/sections/chNN/X.tex"""
    return path.replace("manuscript/sections/", "manuscript/uk/sections/", 1)


def read_record():
    if not os.path.exists(RECORD):
        return []
    header, rows = common.read_tsv(RECORD)
    if header != RECORD_COLS:
        sys.exit("translations.tsv: header is %r, expected %r" % (header, RECORD_COLS))
    return rows


def write_record(rows):
    with open(RECORD, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter="\t", lineterminator="\n")
        w.writerow(RECORD_COLS)
        for r in rows:
            w.writerow([r[c] for c in RECORD_COLS])


def expected(order, record):
    have = {r["path"]: r for r in record}
    out = [HEAD]
    for o in order:
        rel = os.path.relpath(os.path.join(common.REPO, o["path"]),
                              os.path.join(common.REPO, "manuscript"))[:-4]
        if o["path"] in have:
            uk = os.path.relpath(os.path.join(common.REPO, have[o["path"]]["uk_path"]),
                                 os.path.join(common.REPO, "manuscript"))[:-4]
            out.append("\\selectlanguage{ukrainian}\\input{%s}\n" % uk)
        else:
            out.append("\\selectlanguage{english}\\input{%s}\n" % rel)
    return "".join(out)


def head_and_label(path):
    """The heading command and the label line, which a translation must keep:
    the label so every \\ref resolves, the command so the structure holds."""
    cmd = label = None
    for line in open(path, encoding="utf-8"):
        m = common.TEX_HEAD_RE.match(line)
        if m and cmd is None:
            cmd = m.group(1)
        m = common.TEX_LABEL_RE.match(line)
        if m and label is None:
            label = line.strip()
    return cmd, label


def stale(order, record):
    sha = {o["path"]: o["sha256"] for o in order}
    return [r for r in record if sha.get(r["path"]) != r["source_sha256"]]


def check(order, record):
    errors = []
    paths = {o["path"] for o in order}
    for r in record:
        if r["path"] not in paths:
            errors.append("%s: not in ORDER.tsv" % r["path"])
            continue
        if r["uk_path"] != uk_path_for(r["path"]):
            errors.append("%s: uk_path %s, expected %s" % (r["path"], r["uk_path"], uk_path_for(r["path"])))
        if not re.fullmatch(r"[0-9a-f]{64}", r["source_sha256"]):
            errors.append("%s: source_sha256 is not a sha256" % r["path"])
        if r["status"] not in STATUSES:
            errors.append("%s: status %r, expected one of %s" % (r["path"], r["status"], STATUSES))
        ukf = os.path.join(common.REPO, r["uk_path"])
        if not os.path.exists(ukf):
            errors.append("%s: missing" % r["uk_path"])
            continue
        if head_and_label(ukf) != head_and_label(os.path.join(common.REPO, r["path"])):
            errors.append("%s: heading command or label differs from the English" % r["uk_path"])
    if len({r["path"] for r in record}) != len(record):
        errors.append("translations.tsv: a section is recorded twice")
    listed = {r["uk_path"] for r in record}
    for f in sorted(glob.glob(os.path.join(UK, "sections", "ch*", "*.tex"))):
        rel = os.path.relpath(f, common.REPO)
        if rel not in listed:
            errors.append("%s: not recorded in translations.tsv" % rel)
    if os.path.exists(GLOSSARY):
        header, rows = common.read_tsv(GLOSSARY)
        if header != GLOSSARY_COLS:
            errors.append("glossary.tsv: header is %r, expected %r" % (header, GLOSSARY_COLS))
        else:
            seen = set()
            for g in rows:
                if g["status"] not in ("proposed", "approved"):
                    errors.append("glossary.tsv: %r has status %r" % (g["en"], g["status"]))
                if g["en"] in seen:
                    errors.append("glossary.tsv: %r listed twice" % g["en"])
                seen.add(g["en"])
    got = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if got != expected(order, record):
        errors.append("uk/sections.tex is stale: run finishing/tools/uk_edition.py")
    return errors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--stale", action="store_true")
    ap.add_argument("--record", metavar="PATH")
    ap.add_argument("--status", choices=STATUSES)
    ap.add_argument("--by")
    ap.add_argument("--date", default=datetime.date.today().isoformat())
    a = ap.parse_args()
    order = [o for o in common.order_rows()]
    record = read_record()

    if a.record:
        if not (a.status and a.by):
            sys.exit("--record needs --status and --by")
        row = next((o for o in order if o["path"] == a.record), None)
        if row is None:
            sys.exit("%s is not in ORDER.tsv" % a.record)
        if not os.path.exists(os.path.join(common.REPO, uk_path_for(a.record))):
            sys.exit("%s does not exist; write the translation first" % uk_path_for(a.record))
        new = {"path": a.record, "uk_path": uk_path_for(a.record), "source_sha256": row["sha256"],
               "status": a.status, "by": a.by, "date": a.date}
        record = [r for r in record if r["path"] != a.record] + [new]
        seq = {o["path"]: i for i, o in enumerate(order)}
        record.sort(key=lambda r: seq.get(r["path"], 1 << 30))
        write_record(record)
        print("recorded %s (%s, %s) against English %s" % (a.record, a.status, a.by, row["sha256"][:12]))

    st = stale(order, record)
    if a.stale or a.check:
        for r in st:
            print("STALE: %s (translated from %s; English is now different)" % (r["uk_path"], r["source_sha256"][:12]))
    if a.stale:
        return 0
    if a.check:
        errors = check(order, record)
        for e in errors:
            print("ERROR: %s" % e)
        if errors:
            return 1
        print("Ukrainian edition OK: %d of %d section files translated, %d stale"
              % (len(record), len(order), len(st)))
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(expected(order, record))
    print("wrote %s (%d of %d sections translated, %d stale)"
          % (os.path.relpath(OUT, common.REPO), len(record), len(order), len(st)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
